//! The stamp is one value per commit however the tree is checked out or
//! packaged (ruling STAMP-LOCK, F0.6).
//!
//! The build script has no library of its own (glia-stamp carries zero
//! dependencies on purpose), so this test compiles `build.rs` as a module and
//! drives its helpers over small fixture workspaces under `CARGO_TARGET_TMPDIR`.

