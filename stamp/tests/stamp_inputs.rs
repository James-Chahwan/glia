#[test]
fn b_pruning_out_of_closure_members_keeps_the_lock_digest() {
    let full = closure(FULL_LOCK);
    let pruned = pruned_lock();
    assert!(!pruned.contains("glia-py") && !pruned.contains("pyo3"));
    assert!(pruned.contains(" \"getrandom\","));
    assert_eq!(full, closure(&pruned));
    assert!(
        !full.contains("glia-py")
            && !full.contains("glia-toy-domain")
            && !full.contains("pyo3")
            && !full.contains("inventory")
            && !full.contains("target-lexicon")
            && !full.contains("getrandom 0.2.16"),
        "out-of-closure packages are not hashed:\n{full}"
    );
    assert!(full.contains("tree-sitter-python 0.25.0"));

    // The same through the whole stamp: a workspace whose lock was pruned.
    let ws_full = scratch("lock-full/glia");
    let ws_pruned = scratch("lock-pruned/glia");
    fixture(&ws_full);
    fixture(&ws_pruned);
    write(&ws_pruned.join("Cargo.lock"), &pruned);
    assert_eq!(inputs_and_stamp(&ws_full), inputs_and_stamp(&ws_pruned));
}

#[test]
fn c_a_grammar_version_or_checksum_change_moves_the_digest() {
    let base = closure(FULL_LOCK);
    let bumped = FULL_LOCK.replace(
        "name = \"tree-sitter-python\"\nversion = \"0.25.0\"",
        "name = \"tree-sitter-python\"\nversion = \"0.25.1\"",
    );
    assert_ne!(bumped, FULL_LOCK);
    assert_ne!(
        base,
        closure(&bumped),
        "a grammar version bump must move the stamp"
    );
    let rechecked = FULL_LOCK.replace(
        "7777777777777777777777777777777777777777777777777777777777777777",
        "8888888888888888888888888888888888888888888888888888888888888888",
    );
    assert_ne!(
        base,
        closure(&rechecked),
        "a grammar checksum change must move the stamp"
    );

    // An out-of-closure package's bump does not.
    let py_bump = FULL_LOCK.replace("version = \"0.25.1\"", "version = \"0.26.0\"");
    assert_ne!(py_bump, FULL_LOCK);
    assert_eq!(base, closure(&py_bump));
}

#[test]
fn d_a_closure_packages_new_dependency_moves_the_digest() {
    let base = closure(FULL_LOCK);
    let added = FULL_LOCK
        .replace(
            "name = \"glia-graph\"\nversion = \"0.5.3\"\ndependencies = [\n \"glia-core\",\n]",
            "name = \"glia-graph\"\nversion = \"0.5.3\"\ndependencies = [\n \"glia-core\",\n \"smallvec\",\n]",
        )
        .replace(
            "[[package]]\nname = \"target-lexicon\"",
            "[[package]]\nname = \"smallvec\"\nversion = \"1.15.1\"\nsource = \"registry+https://github.com/rust-lang/crates.io-index\"\nchecksum = \"9999999999999999999999999999999999999999999999999999999999999999\"\n\n[[package]]\nname = \"target-lexicon\"",
        );
    assert!(added.contains("\"smallvec\","));
    assert_ne!(
        base,
        closure(&added),
        "a new dependency of a hashed crate must move the stamp"
    );

    // An edge to a package already in the closure moves it too.
    let edge = FULL_LOCK.replace(
        "name = \"glia-store\"\nversion = \"0.5.3\"\ndependencies = [\n \"glia-core\",\n]",
        "name = \"glia-store\"\nversion = \"0.5.3\"\ndependencies = [\n \"glia-code-domain\",\n \"glia-core\",\n]",
    );
    assert_ne!(edge, FULL_LOCK);
    assert_ne!(base, closure(&edge));
}

#[test]
fn an_unreadable_lock_is_refused() {
    for bad in [
        "version = 4\n\n[[package]]\nname = \"glia-core\"\nversion = 0.5.3\n",
        "version = 4\n\n[[package]]\nname = \"glia-core\"\nversion = \"0.5.3\"\ndependencies = [\n \"missing\",\n]\n",
        "version = 4\n\n[[package]]\nname = \"glia-core\"\nversion = \"0.5.3\"\n\n[weird]\n",
        "version = 4\n\n[[package]]\nname = \"glia-core\"\nversion = \"0.5.3\"\ndependencies = [\n \"x\",\n",
    ] {
        assert!(
            build::lock_closure(bad, &["glia-core".to_string()]).is_err(),
            "accepted:\n{bad}"
        );
    }
    assert!(build::lock_closure(FULL_LOCK, &["glia-nope".to_string()]).is_err());
}

