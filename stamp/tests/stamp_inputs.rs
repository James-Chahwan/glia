/// `FULL_LOCK` as cargo rewrites it once glia-py and glia-toy-domain leave the
/// workspace (what `maturin sdist` of glia-cli does): their exclusive packages
/// go, and `getrandom` is locked at one version again, so glia-core's entry
/// loses its version.
fn pruned_lock() -> String {
    let mut out = String::new();
    for block in FULL_LOCK.split("\n\n") {
        let drop = [
            "name = \"glia-py\"",
            "name = \"glia-toy-domain\"",
            "name = \"inventory\"",
            "name = \"pyo3\"",
            "name = \"target-lexicon\"",
            "version = \"0.2.16\"",
        ]
        .iter()
        .any(|needle| block.contains(needle));
        if !drop {
            out.push_str(block);
            out.push_str("\n\n");
        }
    }
    out.replace(" \"getrandom 0.3.4\",", " \"getrandom\",")
}

fn seeds() -> Vec<String> {
    [
        "glia-core",
        "glia-code-domain",
        "glia-graph",
        "glia-engine",
        "glia-store",
        "glia-activation",
        "glia-build-domain",
    ]
    .iter()
    .map(|s| s.to_string())
    .collect()
}

fn closure(lock: &str) -> String {
    match build::lock_closure(lock, &seeds()) {
        Ok(text) => text,
        Err(e) => panic!("lock_closure refused a readable lock: {e}"),
    }
}

fn write(path: &Path, text: &str) {
    if let Some(dir) = path.parent() {
        fs::create_dir_all(dir).unwrap();
    }
    fs::write(path, text).unwrap();
}

/// A minimal workspace holding every hashed root: a manifest and `src/` per
/// crate, plus `tests/`, `examples/` and `benches/` sources that must never be
/// hashed.
fn fixture(ws: &Path) {
    if ws.exists() {
        fs::remove_dir_all(ws).unwrap();
    }
    for (root, name) in [
        ("core", Some("glia-core")),
        ("code-domain", Some("glia-code-domain")),
        ("graph", Some("glia-graph")),
        ("engine", Some("glia-engine")),
        ("store", Some("glia-store")),
        ("activation", Some("glia-activation")),
        ("build-domain", Some("glia-build-domain")),
        ("parsers", None),
    ] {
        let dir = ws.join(root);
        fs::create_dir_all(&dir).unwrap();
        if let Some(name) = name {
            write(
                &dir.join("Cargo.toml"),
                &format!("[package]\nname = \"{name}\"\nversion.workspace = true\n"),
            );
            write(&dir.join("src/lib.rs"), &format!("//! {name}\n"));
            write(&dir.join("tests/it.rs"), "#[test] fn t() {}\n");
            write(&dir.join("examples/ex.rs"), "fn main() {}\n");
            write(&dir.join("benches/b.rs"), "fn main() {}\n");
        }
    }
    let py = ws.join("parsers/code/python");
    write(
        &py.join("Cargo.toml"),
        "[package]\nname = \"glia-parser-python\"\n",
    );
    write(&py.join("src/lib.rs"), "pub fn parse() {}\n");
    write(&py.join("tests/grammar.rs"), "#[test] fn g() {}\n");
    write(&ws.join("Cargo.lock"), FULL_LOCK);
}

fn scratch(name: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_TARGET_TMPDIR"))
        .join("glia-stamp-inputs")
        .join(name)
}

fn inputs_and_stamp(ws: &Path) -> (Vec<String>, u64) {
    let inputs = match build::collect(ws) {
        Ok(i) => i,
        Err(e) => panic!("collect failed on {}: {e}", ws.display()),
    };
    let stamp = match build::stamp(&inputs) {
        Ok(s) => s,
        Err(e) => panic!("stamp failed on {}: {e}", ws.display()),
    };
    (inputs.files.keys().cloned().collect(), stamp)
}

#[test]
fn a_tree_under_a_src_directory_hashes_the_same_inputs_and_stamp() {
    let plain = scratch("plain/glia");
    let under_src = scratch("cache/sdists/src/glia");
    fixture(&plain);
    fixture(&under_src);
    let (keys_plain, stamp_plain) = inputs_and_stamp(&plain);
    let (keys_src, stamp_src) = inputs_and_stamp(&under_src);
    assert!(
        keys_plain.iter().all(|k| !k.contains("/tests/")
            && !k.contains("/examples/")
            && !k.contains("/benches/")),
        "only crate src/ sources and manifests are inputs: {keys_plain:?}"
    );
    assert_eq!(
        keys_plain, keys_src,
        "the checkout's absolute path must not change the input set"
    );
    assert_eq!(stamp_plain, stamp_src);
}

#[test]
