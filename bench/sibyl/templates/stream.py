def kotlin(tr, ax, f, pack):
    ws, call, contract = ax["wiring_source"], ax["wiring_call"], ax["contract"]
    o = Out()
    m = payload.model("kotlin", contract, f, NOTE)
    o.api.update(m.files)
    imports = list(m.imports)
    if call == "direct":
        text, imps, raw, deps = KT_DIRECT[tr]
        imports += imps
        tgt = target(tr, "kotlin", ws, o, imports, whole=True)
        body = fill(text, ty=m.ty, target=tgt, broker=BROKER, decode=fill(m.decode, v=raw))
    else:
        rel, text, fn, raw, deps = KT_HELPER[tr]
        o.api[KT_API + rel] = fill(text, host=WS_HOST, broker=BROKER)
        tgt = target(tr, "kotlin", ws, o, imports, whole=False)
        body = fill(
            """
            fun watchUser(onUser: (<<ty>>) -> Unit) {
                <<fn>>(<<target>>) { <<raw>> -> onUser(<<decode>>) }
            }
            """,
            ty=m.ty, fn=fn, target=tgt, raw=raw, decode=fill(m.decode, v=raw),
        )
    o.deps = deps + [d for d in m.deps if d not in deps]
    o.api[KT_API + "Users.kt"] = block("package com.sibyl.api", "", *sorted(set(imports))) \
        + "\n" + body
    o.call = KT_API + "Users.kt"
    read = payload.read("kotlin", contract, "user", f)
    email = 'user.getString("email")' if contract == "plain-literal" else "user.email"
    o.app["com/sibyl/web/Profile.kt"] = block(
        "package com.sibyl.web", "", "import com.sibyl.api.watchUser", "",
        "fun showUser(render: (String) -> Unit) {",
        f'    watchUser {{ user -> render("${{{read}}} <${{{email}}}>") }}', "}")
    o.reader = "com/sibyl/web/Profile.kt"
    return o


