"""The message clients the WebSocket and queue transports share: a client that receives the
server's `User` messages and an app file reading the renamed field off each one.

`client(tr, ax, field, pack)` -> rest_clients.Out for `tr` = `websocket` or `queue`. The api
file holds `watchUser` (a callback in TypeScript, Kotlin and Swift, a Stream in Dart, an async
iterator in Python); `direct` connects there, `wrapper` goes through a hand-written helper
(`openSocket(path)` / `subscribe(topic)`) in its own file. The libraries are each platform's
usual one: the WebSocket API, web_socket_channel, OkHttp, URLSessionWebSocketTask and
`websockets`; kafkajs, kafka-clients and aiokafka."""

from . import payload
from .channel import KT_API, app_import, block, channel_parts, strlit
from .common import fill
from .rest_clients import Out

WS_HOST = "ws://localhost:8080"
WS_PATH = "/ws/users"
TOPIC = "users.updated"
BROKER = "localhost:9092"
NOTE = "This file was generated by quicktype from the message schema. Do not edit."


def target(tr, lang, ws, o, imports, whole):
    """The connection target: a WebSocket URL (`whole`) or path, or a queue topic."""
    if tr == "queue":
        parts = channel_parts(lang, ws, o, imports, TOPIC, ("USER_UPDATED_TOPIC", TOPIC, ""),
                              ("TopicKey", "", ".updated"))
    else:
        parts = channel_parts(lang, ws, o, imports, WS_PATH, ("WS_PREFIX", "/ws", "/users"),
                              ("RouteKey", "/ws/", ""))
        if whole:
            parts = [("lit", WS_HOST)] + parts
    merged = []
    for k, v in parts:
        if merged and k == "lit" and merged[-1][0] == "lit":
            merged[-1] = ("lit", merged[-1][1] + v)
        else:
            merged.append((k, v))
    return strlit(lang, merged)


