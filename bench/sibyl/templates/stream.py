def swift(tr, ax, f, pack):
    if tr != "websocket":
        raise KeyError("an iOS client holds no broker connection (queue x swift is unexpressible)")
    ws, call, contract = ax["wiring_source"], ax["wiring_call"], ax["contract"]
    o = Out()
    m = payload.model("swift", contract, f, NOTE)
    o.api.update(m.files)
    if call == "direct":
        tgt = target(tr, "swift", ws, o, [], whole=True)
        body = fill(
            """
            public func watchUser(onUser: @escaping (<<ty>>) -> Void) -> URLSessionWebSocketTask {
                let task = URLSession.shared.webSocketTask(with: URL(string: <<target>>)!)
                task.receive { result in
                    guard case .success(.string(let text)) = result else { return }
                    do {
                        let data = Data(text.utf8)
                        onUser(<<decode>>)
                    } catch {
                        return
                    }
                }
                task.resume()
                return task
            }
            """,
            ty=m.ty, target=tgt, decode=fill(m.decode, v="data"),
        )
    else:
        o.api["Socket.swift"] = fill(
            """
            import Foundation

            public enum Socket {
                static let host = "<<host>>"

                public static func open(_ path: String, onData: @escaping (Data) -> Void) -> URLSessionWebSocketTask {
                    let task = URLSession.shared.webSocketTask(with: URL(string: host + path)!)
                    task.receive { result in
                        if case .success(.string(let text)) = result {
                            onData(Data(text.utf8))
                        }
                    }
                    task.resume()
                    return task
                }
            }
            """,
            host=WS_HOST,
        )
        tgt = target(tr, "swift", ws, o, [], whole=False)
        body = fill(
            """
            public func watchUser(onUser: @escaping (<<ty>>) -> Void) -> URLSessionWebSocketTask {
                Socket.open(<<target>>) { data in
                    guard let user = try? <<decode>> else { return }
                    onUser(user)
                }
            }
            """,
            ty=m.ty, target=tgt, decode=fill(m.decode, v="data").removeprefix("try "),
        )
    o.api["Users.swift"] = "import Foundation\n\n" + body
    o.call = "Users.swift"
    read = payload.read("swift", contract, "user", f)
    email = '(user["email"] as? String ?? "")' if contract == "plain-literal" else "user.email"
    head = app_import("swift", pack, "", [])
    o.app["Profile.swift"] = block(
        head, "" if head else None, "public func showUser(render: @escaping (String) -> Void) {",
        f'    _ = watchUser {{ user in render("\\({read}) <\\({email})>") }}', "}")
    o.reader = "Profile.swift"
    return o


