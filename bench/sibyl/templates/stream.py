def ts(tr, ax, f, pack):
    ws, call, contract = ax["wiring_source"], ax["wiring_call"], ax["contract"]
    o = Out()
    m = payload.model("ts", contract, f, NOTE)
    o.api.update(m.files)
    o.deps += m.deps
    imports = list(m.imports)
    if call == "direct":
        if tr == "queue":
            o.deps.append("kafkajs")
            imports.insert(0, "import { Kafka } from 'kafkajs';")
        tgt = target(tr, "ts", ws, o, imports, whole=True)
        body = fill(TS_DIRECT[tr], ty=m.ty, target=tgt, broker=BROKER,
                    decode=fill(m.decode, v=TS_RAW[tr]))
    else:
        rel, fn, helper = TS_HELPER[tr]
        if tr == "queue":
            o.deps.append("kafkajs")
        o.api[rel] = fill(helper, host=WS_HOST, broker=BROKER)
        imports.insert(0, f"import {{ {fn} }} from './{rel[:-3]}';")
        tgt = target(tr, "ts", ws, o, imports, whole=False)
        raw = "data" if tr == "websocket" else "value"
        body = fill(TS_WRAPPED[tr], ty=m.ty, target=tgt, decode=fill(m.decode, v=raw))
    o.api["users.ts"] = block(*imports) + "\n" + body
    o.call, o.exports = "users.ts", ["users"]
    ret = "void" if tr == "websocket" else "Promise<void>"
    o.app["profile.ts"] = fill(
        """
        <<imp>>

        export <<async>>function showUser(render: (label: string) => void): <<ret>> {
          <<aw>>watchUser((user) => render(`${<<read>>} <${user.email}>`));
        }
        """,
        imp=app_import("ts", pack, "users", ["watchUser"]),
        ret=ret, aw="await " if tr == "queue" else "",
        read=payload.read("ts", contract, "user", f),
        **{"async": "async " if tr == "queue" else ""},
    )
    o.reader = "profile.ts"
    return o


