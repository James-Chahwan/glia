def dart(tr, ax, f, pack):
    if tr != "websocket":
        raise KeyError("a Dart client holds no broker connection (queue x dart is unexpressible)")
    ws, call, contract = ax["wiring_source"], ax["wiring_call"], ax["contract"]
    o = Out(deps=["web_socket_channel"])
    m = payload.model("dart", contract, f, NOTE)
    o.api.update(m.files)
    o.deps += m.deps
    imports = list(m.imports)
    raw = "jsonDecode(message as String) as Map<String, dynamic>"
    if call == "direct":
        imports += ["import 'dart:convert';",
                    "import 'package:web_socket_channel/web_socket_channel.dart';"]
        tgt = target(tr, "dart", ws, o, imports, whole=True)
        body = fill(
            """
            Stream<<<ty>>> watchUser() {
              final channel = WebSocketChannel.connect(Uri.parse(<<target>>));
              return channel.stream.map((message) => <<decode>>);
            }
            """,
            ty=m.ty, target=tgt, decode=fill(m.decode, v=raw),
        )
    else:
        o.api["socket.dart"] = fill(
            """
            import 'dart:convert';

            import 'package:web_socket_channel/web_socket_channel.dart';

            const wsHost = '<<host>>';

            Stream<Map<String, dynamic>> openSocket(String path) {
              final channel = WebSocketChannel.connect(Uri.parse('$wsHost$path'));
              return channel.stream.map((message) => jsonDecode(message as String) as Map<String, dynamic>);
            }
            """,
            host=WS_HOST,
        )
        imports.append("import 'socket.dart';")
        tgt = target(tr, "dart", ws, o, imports, whole=False)
        body = fill(
            """
            Stream<<<ty>>> watchUser() => openSocket(<<target>>).map((data) => <<decode>>);
            """,
            ty=m.ty, target=tgt, decode=fill(m.decode, v="data"),
        )
    o.api["users.dart"] = block(*sorted(set(imports))) + "\n" + body
    o.call, o.exports = "users.dart", ["users.dart"]
    email = "user['email']" if contract == "plain-literal" else "user.email"
    o.app["profile.dart"] = block(
        app_import("dart", pack, "users.dart", []), "",
        "Stream<String> userLabels() =>",
        f"    watchUser().map((user) => '${{{payload.read('dart', contract, 'user', f)}}} "
        f"<${{{email}}}>');")
    o.reader = "profile.dart"
    return o


