"""The GraphQL transport: one root field, `user(id: ID!): User`, with the response field the
server renames at S.

Servers (SDL or code-first, as each stack writes it): gqlgen (schema.graphqls, the generated
models, schema.resolvers.go) under gin; NestJS code-first (`@ObjectType` / `@Resolver`, and the
`schema.gql` Nest writes and repos commit); Apollo Server 4 under Express (a `#graphql`
typeDefs literal); Spring for GraphQL (schema.graphqls, `@QueryMapping`); Strawberry under
FastAPI; async-graphql under axum; Hot Chocolate on ASP.NET Core. `wiring_source=const` holds the
endpoint path in a constant (Spring: the root field's name, since its path is configuration).

Clients: Apollo Client / package:graphql / OkHttp / URLSession / httpx at the use site
(`direct`), a hand-written `gqlRequest(query, variables)` helper (`wrapper`), or the code a
generator writes (`generated-sdk`: graphql-codegen's graphql-request SDK, graphql_codegen,
Apollo Kotlin, Apollo iOS, ariadne-codegen), each with the operation document `GetUser`
selecting the field."""

