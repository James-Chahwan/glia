def _url(lang, ws, o, imports):
    """The endpoint URL expression, in the language's string syntax, with the constant the
    `const` form needs written into the api layer."""
    if ws == "literal":
        return {"ts": f"'{HOST}{PATH}'", "dart": f"'{HOST}{PATH}'", "kotlin": f'"{HOST}{PATH}"',
                "swift": f'"{HOST}{PATH}"', "python": f'"{HOST}{PATH}"'}[lang]
    name = {"ts": "GRAPHQL_PATH", "dart": "graphqlPath", "kotlin": "GRAPHQL_PATH",
            "swift": "graphqlPath", "python": "GRAPHQL_PATH"}[lang]
    rel, text, imp = konst(lang, name, pick(ws, None, PATH))
    o.api[rel] = text
    if imp:
        imports.append(imp)
    return {"ts": f"`{HOST}${{{name}}}`", "dart": f"'{HOST}${name}'",
            "kotlin": f'"{HOST}${name}"', "swift": f'"{HOST}\\({name})"',
            "python": f'f"{HOST}{{{name}}}"'}[lang]


