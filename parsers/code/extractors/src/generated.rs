//! The generated-file classifier (DE.7), one for the gRPC extractor and the engine's
//! provenance pass: protoc and codegen file names ([`generated_by_name`]), and the header
//! comment a code generator writes at the top of a file ([`generated_by_banner`]).
//!
//! The header rule reads only the comment and annotation lines among the first
//! [`BANNER_SCAN_LINES`] lines, so a string literal or a line of code that quotes a header
//! never classifies a file. This file's own phrase table is such a literal, and its test
//! `glia_sources_are_not_generated` pins that neither it nor `grpc.rs` classifies. The
//! phrases are listed on `BANNER_MARKERS` and `EDIT_WARNINGS`, far below this head:
//! nothing in these first lines may quote one.

/// How many lines from the top of a file [`generated_by_banner`] reads.
pub const BANNER_SCAN_LINES: usize = 40;

/// What a file name says about the code in it ([`generated_by_name`]).
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum Generated {
    /// protobuf compiler output (`chat.pb.go`, `chat_pb2.py`, `chat.pbgrpc.dart`):
    /// the engine stamps ORIGIN `generated_proto`.
    Proto,
    /// Another code generator's output (`user.g.dart`, `Settings.Designer.cs`):
    /// the engine stamps ORIGIN `generated`.
    Codegen,
}

/// True when `path` or `source` marks the file as machine-written: a
/// [`generated_by_name`] name of either kind, or a [`generated_by_banner`]
/// header. The gRPC passes skip such a file.
pub fn is_generated(path: &str, source: &str) -> bool {
    generated_by_name(path).is_some() || generated_by_banner(source)
}

/// The kind of generated file `path` names, `None` for a hand-written name.
/// Suffixes are matched ASCII-case-insensitively on the base name; a `.pb.`
/// anywhere in the path, in any case, is protobuf output too (the glia-v3 #5
/// rule). Proto wins over Codegen. Allocation-free: the provenance pass asks
/// it of every node.
pub fn generated_by_name(path: &str) -> Option<Generated> {
    let base = path.rsplit(['/', '\\']).next().unwrap_or_default().as_bytes();
    let ends = |suffix: &str| {
        base.len() >= suffix.len()
            && base[base.len() - suffix.len()..].eq_ignore_ascii_case(suffix.as_bytes())
    };
    let pb = [".pb.", ".PB.", ".Pb.", ".pB."].iter().any(|n| path.contains(n));
    if pb || PROTO_SUFFIXES.iter().any(|s| ends(s)) {
        Some(Generated::Proto)
    } else if CODEGEN_SUFFIXES.iter().any(|s| ends(s)) {
        Some(Generated::Codegen)
    } else {
        None
    }
}

/// protobuf compiler output, by file-name ending: protoc-gen-go /
/// go-grpc / grpc-gateway, the Dart plugin's five files, ts-proto, the
/// Python plugins, and protoc-gen-js / grpc-tools (`.js` and `.d.ts`).
const PROTO_SUFFIXES: &[&str] = &[
    ".pb.go",
    ".pb-grpc.go",
    ".pb.gw.go",
    ".pb.dart",
    ".pbjson.dart",
    ".pbenum.dart",
    ".pbserver.dart",
    ".pbgrpc.dart",
    ".pb.ts",
    "_pb2.py",
    "_pb2_grpc.py",
    "_pb.js",
    "_grpc_pb.js",
    "_pb.d.ts",
];

/// Other generators' output, by file-name ending: Dart build_runner
/// (json_serializable / freezed / auto_route / mockito) and C# source
/// generators and resource / settings designers.
const CODEGEN_SUFFIXES: &[&str] = &[
    ".g.dart",
    ".freezed.dart",
    ".gr.dart",
    ".mocks.dart",
    ".g.cs",
    ".designer.cs",
];

/// How a comment or annotation line starts, after trimming: `//`, `/*` and a
/// block comment's `*` continuation, `#`, SQL / Lua / Haskell `--`, Lisp and
/// ini `;`, an HTML `<!--`, a Visual Basic `'`, and an `@` annotation. Any
/// other line (code, a string literal) never counts.
const COMMENT_STARTS: &[&str] = &["//", "/*", "*", "#", "--", ";", "<!--", "'", "@"];

/// Phrases that alone mark a header line, matched on the ASCII-lower-cased
/// line: Go's convention (`// Code generated by <tool>. DO NOT EDIT.`), the
/// C# `<auto-generated>` block, Java's `@javax.annotation.Generated` and
/// grpc-java's `@GrpcGenerated` annotations. `@generated` (Meta / Cargo /
/// Relay) is matched apart, by [`has_at_generated`].
const BANNER_MARKERS: &[&str] = &[
    "code generated by",
    "<auto-generated",
    "annotation.generated",
    "grpcgenerated",
];

/// The edit warnings a generator writes beside the word `generated`. Neither
/// marks a file on its own: a hand-written `// Do not edit without updating
/// the migration.` is no header. The head must also say `generated` on a
/// comment line (the same line or another, as OpenAPI Generator splits them).
const EDIT_WARNINGS: &[&str] = &["do not edit", "do not modify"];

/// True when the first [`BANNER_SCAN_LINES`] lines of `source` carry a code
/// generator's header: a comment or annotation line (`COMMENT_STARTS`)
/// holding a `BANNER_MARKERS` phrase or an `@generated` tag
/// (`has_at_generated`), or comment lines that between them say `generated`
/// and an `EDIT_WARNINGS` phrase. ASCII case-folded; a leading byte-order mark is
/// ignored. Every rule needs the word `generated`, so a head without it is
/// refused before any line is looked at.
pub fn generated_by_banner(source: &str) -> bool {
    let end = source
        .match_indices('\n')
        .nth(BANNER_SCAN_LINES - 1)
        .map_or(source.len(), |(at, _)| at);
    let head = source[..end].to_ascii_lowercase();
    if !head.contains("generated") {
        return false;
    }
    let mut says_generated = false;
    let mut says_keep_off = false;
    for line in head.lines().take(BANNER_SCAN_LINES) {
        let line = line.trim_start_matches('\u{feff}').trim();
        if !COMMENT_STARTS.iter().any(|p| line.starts_with(p)) {
            continue;
        }
        if BANNER_MARKERS.iter().any(|m| line.contains(m)) || has_at_generated(line) {
            return true;
        }
        says_generated |= line.contains("generated");
        says_keep_off |= EDIT_WARNINGS.iter().any(|w| line.contains(w));
        if says_generated && says_keep_off {
            return true;
        }
    }
    false
}

/// An `@generated` tag in a lower-cased line that starts it or follows a
/// byte that is neither a word byte nor a `.`: `// @generated by tool` and
/// `/** @generated */` hold one, `team@generated.io` does not.
fn has_at_generated(lower: &str) -> bool {
    lower.match_indices("@generated").any(|(at, _)| {
        lower.as_bytes()[..at]
            .last()
            .is_none_or(|b| !(b.is_ascii_alphanumeric() || *b == b'_' || *b == b'.'))
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn proto_names_by_suffix_and_the_pb_rule() {
        for path in [
            "chatpb/chat.pb.go",
            "gen/chat.pb-grpc.go",
            "gen/chat.pb.gw.go",
            "lib/proto/chat.pb.dart",
            "lib/proto/chat.pbjson.dart",
            "lib/proto/chat.pbenum.dart",
            "lib/proto/chat.pbserver.dart",
            "lib/core/generated/quokka_chat.pbgrpc.dart",
            "src/gen/chat.pb.ts",
            "proto/chat_pb2.py",
            "proto/chat_pb2_grpc.py",
            "web/gen/chat_pb.js",
            "web/gen/chat_grpc_pb.js",
            "web/gen/chat_pb.d.ts",
            "web/gen/chat_grpc_pb.d.ts",
            "Gen/Chat.PB.Go",
            "api/x.pb.validate.go",
        ] {
            assert_eq!(generated_by_name(path), Some(Generated::Proto), "{path}");
        }
    }

    #[test]
    fn codegen_names_by_suffix() {
        for path in [
            "lib/user.g.dart",
            "lib/user.freezed.dart",
            "lib/router.gr.dart",
            "test/user_test.mocks.dart",
            "obj/Debug/App.g.cs",
            "Data/Settings.Designer.cs",
            "Properties\\Resources.designer.cs",
        ] {
            assert_eq!(generated_by_name(path), Some(Generated::Codegen), "{path}");
        }
    }

    #[test]
    fn hand_written_names_are_none() {
        for path in [
            "src/chat.go",
            "src/app/chat.component.ts",
            "lib/user.dart",
            "lib/big.dart",
            "Data/Settings.cs",
            "src/designer.cs",
            "db/queries_gen.go",
            "pkg/grpc_pb_util.py",
            "",
        ] {
            assert_eq!(generated_by_name(path), None, "{path}");
        }
    }

    /// The heads of real generators' files, each on its own.
    const HEADS: &[(&str, &str)] = &[
        ("sqlc", "// Code generated by sqlc. DO NOT EDIT.\n// versions:\n//   sqlc v1.25.0\n\npackage db\n"),
        ("stringer", "// Code generated by \"stringer -type=Code\"; DO NOT EDIT.\n\npackage codes\n"),
        ("swaggo", "// Package docs Code generated by swaggo/swag. DO NOT EDIT\npackage docs\n"),
        ("protoc-py", "# -*- coding: utf-8 -*-\n# Generated by the protocol buffer compiler.  DO NOT EDIT!\n# source: chat.proto\n\"\"\"Generated protocol buffer code.\"\"\"\n"),
        ("dart", "//\n//  Generated code. Do not modify.\n//  source: chat.proto\n//\n"),
        ("build_runner", "// GENERATED CODE - DO NOT MODIFY BY HAND\n\npart of 'user.dart';\n"),
        ("openapi", "/**\n * Pet Store API\n * The version of the OpenAPI document: 1.0.0\n *\n * NOTE: This class is auto generated by OpenAPI Generator (https://openapi-generator.tech).\n * https://openapi-generator.tech\n * Do not edit the class manually.\n */\n\npackage org.openapitools.client;\n"),
        ("csharp", "\u{feff}//------------------------------------------------------------------------------\n// <auto-generated>\n//     This code was generated by a tool.\n// </auto-generated>\n//------------------------------------------------------------------------------\n"),
        ("grpc-java", "package io.grpc.examples;\n\nimport static io.grpc.MethodDescriptor.generateFullMethodName;\n\n/**\n */\n@javax.annotation.Generated(\n    value = \"by gRPC proto compiler (version 1.60.0)\",\n    comments = \"Source: helloworld.proto\")\n@io.grpc.stub.annotations.GrpcGenerated\npublic final class GreeterGrpc {\n"),
        ("at-generated", "/**\n * @generated SignedSource<<abc>>\n */\n"),
        ("cargo", "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 3\n"),
        ("sql", "-- Code generated by sqlc. DO NOT EDIT.\nSELECT 1;\n"),
        ("html", "<!-- generated file: do not edit -->\n<div></div>\n"),
        ("vb", "'------------------------------------------------------------------------------\n' <auto-generated>\n' </auto-generated>\nModule M\n"),
    ];

    #[test]
    fn generator_heads_classify() {
        for (what, head) in HEADS {
            assert!(generated_by_banner(head), "{what}: {head}");
            assert!(is_generated("src/plain.go", head), "{what}");
        }
    }

    #[test]
    fn hand_written_heads_do_not_classify() {
        let negatives: &[(&str, &str)] = &[
            ("edit warning without generated", "// Limits. Do not edit without updating the migration.\npackage db\n\nconst MaxUsers = 10\n"),
            ("generated without a warning", "// The IDs are generated by the database.\npackage db\n"),
            ("string literal", "package x\n\nconst banner = \"// Code generated by sqlc. DO NOT EDIT.\"\n"),
            ("code line", "let s = \"<auto-generated>\"; // a constant\n"),
            ("rust literal", "const T: &[&str] = &[\n    \"code generated by\",\n    \"do not edit\",\n];\n"),
            ("email", "// Contact: team@generated.io\npackage x\n"),
            ("dotted tag", "// see x.@generated\npackage x\n"),
            ("word before tag", "// foo@generated\n"),
            ("empty", ""),
        ];
        for (what, source) in negatives {
            assert!(!generated_by_banner(source), "{what}: {source}");
        }
        assert!(!is_generated("db/limits.go", negatives[0].1));
    }

    #[test]
    fn the_head_ends_at_banner_scan_lines() {
        let late = format!("{}// Code generated by sqlc. DO NOT EDIT.\n", "package x\n".repeat(BANNER_SCAN_LINES));
        assert!(!generated_by_banner(&late));
        let last = format!("{}// Code generated by sqlc. DO NOT EDIT.\n", "package x\n".repeat(BANNER_SCAN_LINES - 1));
        assert!(generated_by_banner(&last));
        // The pairing spans lines of the head, never past it.
        let split = format!("// generated\n{}// do not edit\n", "x\n".repeat(BANNER_SCAN_LINES - 2));
        assert!(generated_by_banner(&split));
        let past = format!("// generated\n{}// do not edit\n", "x\n".repeat(BANNER_SCAN_LINES - 1));
        assert!(!generated_by_banner(&past));
    }

    /// The classifier never classifies its own source or the gRPC extractor's,
    /// whose tests quote real headers in string literals.
    #[test]
    fn glia_sources_are_not_generated() {
        assert!(!generated_by_banner(include_str!("generated.rs")));
        assert!(!generated_by_banner(include_str!("grpc.rs")));
        assert!(!is_generated("parsers/code/extractors/src/generated.rs", include_str!("generated.rs")));
    }
}
