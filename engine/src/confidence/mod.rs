//! Calibrated confidence (0.5.7, HC.4): the audited precision of the edge
//! stratum an answer row rests on, shown beside the row's tier.
//!
//! A row's tier (`fact` / `derived` / `heuristic`, [`Tier`]) stays the
//! verdict. `precision` is a measurement of that verdict's stratum: on the
//! audit panel (bench/edge-audit: the 0.5.6 fit audit plus the 0.5.7
//! held-out panel, pooled after the calibration rule in
//! `dev-notes/confidence-gate-0.5.7.md` read `CONFIDENCE: .. -> PASS`), the
//! share of judged edges of that (category, tier[, emitter/rule]) stratum a
//! judge found correct, its Wilson 95% interval, how many were judged, and
//! which audit (the first 12 hex of the blake3 of the calibration.json the
//! table was generated with, [`AUDIT`]).
//!
//! What it is not: a probability that THIS row is right, or a score. It
//! never sorts, filters, ranks, blends, gates or changes a tier or an exit
//! code: every answer computes its rows, order, tiers and blocking first and
//! only then stamps `precision` on the rows (`engine/tests/confidence.rs`
//! pins rows, order and exit codes identical with the key dropped).
//!
//! # The table
//!
//! `table.json` beside this file, generated by `scripts/edge-audit.sh
//! calibrate --emit-table` (`engine/examples/edge_audit.rs`
//! `precision_table`) and read with `include_str!` at query time: a JSON
//! file, not a `.rs` source, so stamp's PARSER_STAMP does not hash it, and
//! nothing that shapes a graph reads it. A re-audit changes no parse cache and
//! no layout. It holds every stratum and sub-stratum with at least 10 judged
//! ids, or a census (every edge of it on the panel judged), each with its
//! `under_floor` flag (pooled p below its tier's floor: fact 0.95, derived
//! 0.90, heuristic 0.70), and the fit report's per-tier estimates.
//!
//! # Lookup
//!
//! An edge's stratum is the one the audit sampled it in: its category, the
//! tier `why::edge_tier` gives it, and its EVIDENCE emitter and rule. The most
//! specific row wins: the sub-stratum `CATEGORY|tier|emitter/rule` when it
//! holds at least [`MIN_SPECIFIC`] judged ids or is a census, else the
//! stratum `CATEGORY|tier`, else the edge is unmeasured (`unmeasured: true`,
//! no interval). Eleven strata of the 0.5.7 table rest on the held-out panel
//! alone (e.g. `NAVIGATES_TO|derived`, 0.200), for which the gate measured no
//! transfer.
//!
//! # A row on several edges
//!
//! A row whose verdict needs every edge (a cycle, a path, a rule row's
//! witness, an implementor's heritage path) shows its weakest link
//! ([`weakest`]: the least lower bound, ties by stratum name, an unmeasured
//! edge weakest of all), named by its stratum: never a product of
//! precisions, which would assume the edges independent. A row any one of
//! whose edges proves it (a forbid_edge rule, a reflexion divergence, whose
//! tier is its strongest edge's) shows the strongest edge of that tier
//! ([`strongest`]). A row whose witness was cut shows none: its weakest link
//! is not known.
//!
//! # Surfaces
//!
//! `glia why`, `check`, `query`, `implementors` and `review` print it in
//! JSON as `"precision":{"lo":..,"p":..,"hi":..,"n":..,"stratum":"..",
//! "audit":".."}` (plus `census` / `under_floor` / `unmeasured` when true) and
//! in markdown beside the tier, `fact (>= 0.88 on CALLS|fact, n=31)` (the
//! lower bound rounded down), `derived (>= 0.56 on DOCUMENTS|derived, n=29,
//! under floor)`, `derived (unmeasured stratum)` ([`tier_text`]);
//! `--no-precision` / `precision=False` drops it ([`Annotated`]). review's
//! counts gain `precision_by_tier`, the audit's per-tier estimates.
//!
//! fired_on, once per answer that printed any (the surface prints it,
//! [`report`]): `[confidence] surface=<s> rows=<r> measured=<m>
//! unmeasured=<u> under_floor=<f> audit=<12 hex>`.

use std::collections::BTreeMap;
use std::sync::LazyLock;

use glia_activation::profile::Tier;
use glia_code_domain::edge_category;
use glia_code_domain::evidence::Evidence;
use glia_core::Edge;
use serde::{Deserialize, Serialize};

use crate::why;

/// The table's text (module doc "The table").
const TABLE_JSON: &str = include_str!("table.json");

/// The audit the shipped table was generated from: the first 12 hex of the
/// blake3 of its calibration.json.
pub const AUDIT: &str = audit_of(TABLE_JSON);

/// A sub-stratum answers for an edge only with this many judged ids, or as a
/// census; below it the edge reads its (category, tier) stratum.
pub const MIN_SPECIFIC: u64 = 30;

/// `"audit": "<12 hex>"`'s value in `json`, at compile time; empty when the
/// table holds none (a unit test pins it against the parsed table).
const fn audit_of(json: &str) -> &str {
    const KEY: &[u8] = b"\"audit\": \"";
    let b = json.as_bytes();
    let mut i = 0;
    while i + KEY.len() + 12 <= b.len() {
        let mut j = 0;
        while j < KEY.len() && b[i + j] == KEY[j] {
            j += 1;
        }
        if j == KEY.len() {
            let (_, rest) = b.split_at(i + KEY.len());
            let (hex, _) = rest.split_at(12);
            return match core::str::from_utf8(hex) {
                Ok(s) => s,
                Err(_) => "",
            };
        }
        i += 1;
    }
    ""
}

fn is_false(b: &bool) -> bool {
    !*b
}

/// The audited precision of the stratum a row rests on (module doc).
#[non_exhaustive]
#[derive(Serialize, Debug, Clone, PartialEq)]
pub struct Precision {
    /// The Wilson 95% lower bound; `None` when unmeasured.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub lo: Option<f64>,
    /// Judged correct / judged; `None` when unmeasured.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub p: Option<f64>,
    /// The Wilson 95% upper bound; `None` when unmeasured.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub hi: Option<f64>,
    /// Judged ids of the stratum (unsure excluded); 0 when unmeasured.
    pub n: u64,
    /// `CATEGORY|tier`, `CATEGORY|tier|emitter/rule`, or for a per-tier
    /// estimate the tier.
    pub stratum: String,
    /// [`AUDIT`] of the table it was read from.
    pub audit: &'static str,
    /// Every edge of the stratum on the panel was judged.
    #[serde(skip_serializing_if = "is_false")]
    pub census: bool,
    /// The pooled p is below the tier's floor.
    #[serde(skip_serializing_if = "is_false")]
    pub under_floor: bool,
    /// The audit judged no (or too few) edges of the stratum.
    #[serde(skip_serializing_if = "is_false")]
    pub unmeasured: bool,
}

impl Precision {
    /// An unmeasured `stratum` of `audit`.
    pub fn unmeasured(stratum: String, audit: &'static str) -> Self {
        Precision {
            lo: None,
            p: None,
            hi: None,
            n: 0,
            stratum,
            audit,
            census: false,
            under_floor: false,
            unmeasured: true,
        }
    }

    /// The audit judged the stratum.
    pub fn measured(&self) -> bool {
        !self.unmeasured
    }
}

#[derive(Deserialize, Debug, Clone)]
struct RowIn {
    stratum: String,
    n: u64,
    p: f64,
    lo: f64,
    hi: f64,
    #[serde(default)]
    census: bool,
    #[serde(default)]
    under_floor: bool,
}

#[derive(Deserialize, Debug, Clone)]
struct TierIn {
    tier: String,
    n: u64,
    p: Option<f64>,
    lo: Option<f64>,
    hi: Option<f64>,
    #[serde(default)]
    under_floor: bool,
}

#[derive(Deserialize, Debug, Clone, Default)]
struct TableIn {
    #[serde(default)]
    audit: String,
    #[serde(default)]
    tiers: Vec<TierIn>,
    #[serde(default)]
    strata: Vec<RowIn>,
    #[serde(default)]
    sub_strata: Vec<RowIn>,
}

/// A precision table: [`Table::shipped`], or [`Table::empty`] (every edge
/// unmeasured).
#[non_exhaustive]
#[derive(Debug, Clone)]
pub struct Table {
    audit: &'static str,
    tiers: BTreeMap<String, TierIn>,
    strata: BTreeMap<String, RowIn>,
    subs: BTreeMap<String, RowIn>,
}

static SHIPPED: LazyLock<Table> = LazyLock::new(|| {
    // The text is generated and pinned by `edge_audit --emit-table --check`
    // and parsed by a unit test: a parse failure here is unreachable, and
    // reads as an empty table rather than a panic.
    // A table whose parsed audit is not the one [`AUDIT`] read is no table.
    let parsed: TableIn = serde_json::from_str(TABLE_JSON)
        .ok()
        .filter(|t: &TableIn| t.audit == AUDIT)
        .unwrap_or_default();
    Table::from_parts(AUDIT, parsed)
});

impl Table {
    /// The table generated from the committed audit (module doc).
    pub fn shipped() -> &'static Table {
        &SHIPPED
    }

    /// A table with no row: every edge unmeasured.
    pub fn empty() -> Table {
        Table::from_parts(AUDIT, TableIn::default())
    }

    fn from_parts(audit: &'static str, t: TableIn) -> Table {
        let by = |rows: Vec<RowIn>| rows.into_iter().map(|r| (r.stratum.clone(), r)).collect();
        Table {
            audit,
            tiers: t.tiers.into_iter().map(|r| (r.tier.clone(), r)).collect(),
            strata: by(t.strata),
            subs: by(t.sub_strata),
        }
    }

    /// The audit digest the table names.
    pub fn audit(&self) -> &'static str {
        self.audit
    }

    fn of_row(&self, r: &RowIn) -> Precision {
        Precision {
            lo: Some(r.lo),
            p: Some(r.p),
            hi: Some(r.hi),
            n: r.n,
            stratum: r.stratum.clone(),
            audit: self.audit,
            census: r.census,
            under_floor: r.under_floor,
            unmeasured: false,
        }
    }

    /// The precision of an edge of `category` (an `edge_category` name) at
    /// `tier` with EVIDENCE `emitter` / `rule` (module doc "Lookup").
    pub fn lookup(
        &self,
        category: &str,
        tier: &str,
        emitter: Option<&str>,
        rule: Option<&str>,
    ) -> Precision {
        let base = format!("{category}|{tier}");
        let sub = format!("{base}|{}/{}", emitter.unwrap_or("-"), rule.unwrap_or("-"));
        if let Some(r) = self
            .subs
            .get(&sub)
            .filter(|r| r.n >= MIN_SPECIFIC || r.census)
        {
            return self.of_row(r);
        }
        match self.strata.get(&base) {
            Some(r) => self.of_row(r),
            None => Precision::unmeasured(base, self.audit),
        }
    }

    /// [`Table::lookup`] of `e`: its category, `why::edge_tier`'s tier, its
    /// EVIDENCE emitter and rule.
    pub fn of_edge(&self, e: &Edge) -> Precision {
        let ev = Evidence::of(e);
        let (tier, _) = why::edge_tier(e);
        self.lookup(
            edge_category::name(e.category),
            tier.as_str(),
            ev.as_ref().map(|ev| ev.emitter.as_str()),
            ev.as_ref().and_then(|ev| ev.rule.as_deref()),
        )
    }

    /// The audit's per-tier estimate of `tier` (the fit report's stratified
    /// estimate); `None` for a tier the audit holds none of.
    pub fn of_tier(&self, tier: &str) -> Option<Precision> {
        let t = self.tiers.get(tier)?;
        Some(Precision {
            lo: t.lo,
            p: t.p,
            hi: t.hi,
            n: t.n,
            stratum: t.tier.clone(),
            audit: self.audit,
            census: false,
            under_floor: t.under_floor,
            unmeasured: t.p.is_none(),
        })
    }
}

/// [`Table::of_edge`] over the shipped table.
pub fn of_edge(e: &Edge) -> Precision {
    Table::shipped().of_edge(e)
}

/// [`Table::lookup`] over the shipped table.
pub fn lookup(category: &str, tier: Tier, emitter: Option<&str>, rule: Option<&str>) -> Precision {
    Table::shipped().lookup(category, tier.as_str(), emitter, rule)
}

/// The weakest link of a row that needs every edge (module doc): the least
/// lower bound, an unmeasured precision weakest of all, ties by stratum name.
/// `None` for no edge.
pub fn weakest<'a>(edges: impl IntoIterator<Item = &'a Precision>) -> Option<Precision> {
    edges
        .into_iter()
        .min_by(|a, b| {
            let key = |p: &Precision| p.lo.filter(|_| p.measured()).unwrap_or(f64::NEG_INFINITY);
            key(a)
                .total_cmp(&key(b))
                .then_with(|| a.stratum.cmp(&b.stratum))
        })
        .cloned()
}

/// The strongest edge of a row any one edge proves (module doc): the
/// greatest lower bound among the measured, ties by stratum name; the least
/// stratum's when none is measured. `None` for no edge.
pub fn strongest<'a>(edges: impl IntoIterator<Item = &'a Precision>) -> Option<Precision> {
    let all: Vec<&Precision> = edges.into_iter().collect();
    let measured = all.iter().filter(|p| p.measured()).min_by(|a, b| {
        let lo = |p: &Precision| p.lo.unwrap_or(f64::NEG_INFINITY);
        lo(b)
            .total_cmp(&lo(a))
            .then_with(|| a.stratum.cmp(&b.stratum))
    });
    measured
        .or_else(|| all.iter().min_by(|a, b| a.stratum.cmp(&b.stratum)))
        .map(|p| (*p).clone())
}

/// `x` rounded DOWN to 2 decimals: a printed lower bound never overstates it.
fn floor2(x: f64) -> f64 {
    (x * 100.0 + 1e-9).floor() / 100.0
}

/// The markdown tier cell (module doc "Surfaces"): `tier` alone without a
/// precision, else `tier (>= <lo> on <stratum>, n=<n>[, census][, under
/// floor])` or `tier (unmeasured stratum)`.
pub fn tier_text(tier: &str, p: Option<&Precision>) -> String {
    let Some(p) = p else {
        return tier.to_string();
    };
    if !p.measured() {
        return format!("{tier} (unmeasured stratum)");
    }
    let mut out = format!(
        "{tier} (>= {:.2} on {}, n={}",
        floor2(p.lo.unwrap_or(0.0)),
        p.stratum,
        p.n
    );
    if p.census {
        out.push_str(", census");
    }
    if p.under_floor {
        out.push_str(", under floor");
    }
    out.push(')');
    out
}

/// What an answer's `precision` keys hold, for the marker.
#[non_exhaustive]
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct Tally {
    /// Rows carrying a `precision`.
    pub rows: usize,
    pub measured: usize,
    pub unmeasured: usize,
    /// Measured rows whose stratum is under its tier's floor.
    pub under_floor: usize,
}

impl Tally {
    /// Count one row's precision.
    pub fn add(&mut self, p: Option<&Precision>) {
        let Some(p) = p else {
            return;
        };
        self.rows += 1;
        if p.measured() {
            self.measured += 1;
            if p.under_floor {
                self.under_floor += 1;
            }
        } else {
            self.unmeasured += 1;
        }
    }
}

/// An answer that carries `precision` keys: the surfaces drop them
/// (`--no-precision`, `precision=False`) or count them for the marker.
pub trait Annotated {
    /// Remove every `precision` (and `precision_by_tier`) the answer holds.
    fn drop_precision(&mut self);
    /// Count the rows that carry one.
    fn precision_tally(&self) -> Tally;
}

/// A surface's last step: with `keep` print the marker (when any row carries
/// a precision), else drop every key.
pub fn finish(answer: &mut impl Annotated, keep: bool, surface: &str) {
    if keep {
        report(surface, answer.precision_tally());
    } else {
        answer.drop_precision();
    }
}

/// The fired_on line, when `t` counts a row.
pub fn report(surface: &str, t: Tally) {
    if t.rows == 0 {
        return;
    }
    eprintln!(
        "[confidence] surface={surface} rows={} measured={} unmeasured={} under_floor={} audit={AUDIT}",
        t.rows, t.measured, t.unmeasured, t.under_floor
    );
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn shipped_table_parses_and_names_its_audit() {
        let parsed: TableIn = serde_json::from_str(TABLE_JSON).expect("table.json parses");
        assert_eq!(parsed.audit, AUDIT);
        assert_eq!(AUDIT.len(), 12);
        assert!(AUDIT.bytes().all(|b| b.is_ascii_hexdigit()), "{AUDIT}");
        assert!(!parsed.strata.is_empty() && !parsed.tiers.is_empty());
        assert_eq!(Table::shipped().strata.len(), parsed.strata.len());
    }

    #[test]
    fn lookup_prefers_a_big_sub_stratum_then_the_stratum() {
        let row = |s: &str, n, census| RowIn {
            stratum: s.to_string(),
            n,
            p: 0.9,
            lo: 0.8,
            hi: 0.95,
            census,
            under_floor: false,
        };
        let t = Table::from_parts(
            "000000000000",
            TableIn {
                audit: String::new(),
                tiers: Vec::new(),
                strata: vec![row("CALLS|fact", 40, false)],
                sub_strata: vec![
                    row("CALLS|fact|graph:calls/self", 31, false),
                    row("CALLS|fact|graph:calls/bare", 12, false),
                    row("CALLS|fact|graph:calls/tiny", 3, true),
                ],
            },
        );
        let at = |r| {
            t.lookup("CALLS", "fact", Some("graph:calls"), Some(r))
                .stratum
        };
        assert_eq!(at("self"), "CALLS|fact|graph:calls/self");
        assert_eq!(at("bare"), "CALLS|fact", "n 12 < 30 reads the stratum");
        assert_eq!(at("tiny"), "CALLS|fact|graph:calls/tiny", "a census");
        let none = t.lookup("USES", "derived", None, None);
        assert!(none.unmeasured && none.stratum == "USES|derived");
        assert!(
            Table::empty()
                .lookup("CALLS", "fact", None, None)
                .unmeasured
        );
    }

    #[test]
    fn weakest_and_strongest_name_one_stratum() {
        let p = |s: &str, lo: Option<f64>| Precision {
            lo,
            p: lo,
            hi: lo,
            n: if lo.is_some() { 30 } else { 0 },
            stratum: s.to_string(),
            audit: "x",
            census: false,
            under_floor: false,
            unmeasured: lo.is_none(),
        };
        let a = p("A|fact", Some(0.9));
        let b = p("B|fact", Some(0.7));
        let c = p("C|fact", Some(0.7));
        let u = p("U|derived", None);
        assert_eq!(
            weakest([&a, &c, &b]).map(|x| x.stratum),
            Some("B|fact".into())
        );
        assert_eq!(
            weakest([&a, &u]).map(|x| x.stratum),
            Some("U|derived".into())
        );
        assert_eq!(
            strongest([&b, &u, &a]).map(|x| x.stratum),
            Some("A|fact".into())
        );
        assert_eq!(strongest([&u]).map(|x| x.stratum), Some("U|derived".into()));
        assert!(weakest([]).is_none());
    }

    #[test]
    fn tier_text_rounds_the_lower_bound_down() {
        let mut p = Precision::unmeasured("CALLS|fact".into(), "x");
        assert_eq!(tier_text("fact", Some(&p)), "fact (unmeasured stratum)");
        p.unmeasured = false;
        p.lo = Some(0.886);
        p.n = 31;
        assert_eq!(
            tier_text("fact", Some(&p)),
            "fact (>= 0.88 on CALLS|fact, n=31)"
        );
        p.under_floor = true;
        assert_eq!(
            tier_text("fact", Some(&p)),
            "fact (>= 0.88 on CALLS|fact, n=31, under floor)"
        );
        assert_eq!(tier_text("fact", None), "fact");
    }
}
