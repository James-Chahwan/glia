#[test]
fn file_space_and_counts() {
    let b = build(&main_tree_files(), Some(&main_history()));
    let cache = RankCache::new("answer", &b.roots, &b.labels);
    let files = cache.files(&b.merged);
    let paths: Vec<&str> = (0..files.len() as u32).map(|f| files.path(f)).collect();
    let mut sorted = paths.clone();
    sorted.sort_unstable();
    assert_eq!(paths, sorted, "paths sorted");
    for absent in ["README.md", "conf/app.yaml", PB] {
        assert!(!paths.contains(&absent), "{absent} is no candidate: {paths:?}");
    }
    assert!(paths.iter().all(|p| !p.starts_with("docs/")), "{paths:?}");
    assert_eq!(files.generated(), 1, "svc/pb.py is ORIGIN generated");
    for p in [CORE, A, B, C, PAGE] {
        let f = ix(&files, p);
        assert!(!files.nodes(f).is_empty(), "{p} has nodes");
        assert!(files.nodes(f).iter().all(|&n| files.file_of_node(n) == Some(f)));
    }
    assert!(files.degree(ix(&files, CORE)) > 0.0);
    assert_eq!(files.len(), 5 + 30);

    let co = cache.cochange(&b.merged);
    let s = co.stats();
    assert_eq!((s.repos, s.snapshots, s.missing, s.commits), (1, 1, 0, 17));
    assert_eq!(s.train_commits, 16, "the 31-candidate commit trains nothing");
    let (core, a, bb, c, page) = (ix(&files, CORE), ix(&files, A), ix(&files, B), ix(&files, C), ix(&files, PAGE));
    assert_eq!(co.count(core), 5 + 4 + 2 + 3 + 1 + 1);
    assert_eq!(co.count(c), 5);
    assert_eq!(co.count(ix(&files, &gen_file(0))), 0);
    let n = files.len();
    let one = c0(&*co, &[core], n);
    assert_eq!(one[c as usize], 5.0 / 17.0);
    assert_eq!(one[page as usize], 4.0 / 17.0);
    assert_eq!(one[bb as usize], 2.0 / 17.0);
    assert_eq!(one[a as usize], 0.0);
    let two = c0(&*co, &[core, c], n);
    assert_eq!(two[core as usize], 5.0 / 6.0);
    assert_eq!(two[c as usize], 5.0 / 17.0);
    assert_eq!(two[page as usize], 4.0 / 17.0);

    // from_counts over the same counts: bit-equal C0.
    let count: Vec<u32> = (0..n as u32).map(|f| co.count(f)).collect();
    let pairs: Vec<Vec<(u32, u32)>> = (0..n as u32).map(|f| co.cochanged(f).iter().rev().copied().collect()).collect();
    let kept = CochangeIndex::from_counts(count, pairs);
    for seeds in [vec![core], vec![core, c], vec![c, page, core]] {
        let bits = |v: Vec<f64>| v.into_iter().map(f64::to_bits).collect::<Vec<_>>();
        assert_eq!(bits(c0(&kept, &seeds, n)), bits(c0(&*co, &seeds, n)), "{seeds:?}");
    }
    assert_eq!(kept.stats().pairs, s.pairs);

    // a given index replaces the snapshot read; same file space.
    let given = RankCache::new("answer", &b.roots, &b.labels).with_cochange(CochangeIndex::from_counts(vec![0; n], vec![]));
    assert_eq!(given.cochange(&b.merged).stats().pairs, 0);
}

/// Old-path commits are no commits of the renamed file (no rename fold).
#[test]
fn renames_are_not_folded() {
    const X: &str = "svc/x.py";
    const Y: &str = "svc/y.py";
    const OLD: &str = "svc/old_x.py";
    let tree: Vec<(String, String)> = vec![
        (X.into(), "def x_fn():\n    return 1\n".into()),
        (Y.into(), "def y_fn():\n    return 2\n".into()),
    ];
    let h = commits(vec![
        (plain(&[OLD, Y]), 2),
        (vec![file(X, Some(OLD)), file(Y, None)], 1),
        (plain(&[X, Y]), 1),
    ]);
    let b = build(&tree, Some(&h));
    let cache = RankCache::new("answer", &b.roots, &b.labels);
    let files = cache.files(&b.merged);
    let co = cache.cochange(&b.merged);
    let (x, y) = (ix(&files, X), ix(&files, Y));
    assert_eq!(co.count(y), 4);
    assert_eq!(co.count(x), 2);
    let n = files.len();
    assert_eq!(c0(&*co, &[y], n)[x as usize], 2.0 / 5.0);
    assert_eq!(c0(&*co, &[x], n)[y as usize], 2.0 / 3.0);
}

#[test]
fn no_snapshot_is_an_empty_index() {
    let b = build(&main_tree_files(), None);
    let cache = RankCache::new("answer", &b.roots, &b.labels);
    let co = cache.cochange(&b.merged);
    let s = co.stats();
    assert_eq!((s.repos, s.snapshots, s.missing, s.train_commits, s.files, s.pairs), (1, 0, 1, 0, 0, 0));
    let none = RankCache::new("answer", &BTreeMap::new(), &b.labels);
    assert_eq!(none.cochange(&b.merged).stats().repos, 0);
}

/// On a real tree with a history snapshot (`glia history sync <root>` first):
/// `GLIA_RANK_ROOT=<root> cargo test -p glia-engine --test rank_cochange --
/// --ignored glia_snapshot_stats --nocapture`; prints the two markers.
#[test]
#[ignore]
fn glia_snapshot_stats() {
    let root = std::env::var("GLIA_RANK_ROOT")
        .unwrap_or_else(|_| format!("{}/..", env!("CARGO_MANIFEST_DIR")));
    let r = generate_one(&root).expect("build");
    let cache = RankCache::new("answer", &r.repo_roots, &r.repo_labels);
    let files = cache.files(&r.merged);
    let co = cache.cochange(&r.merged);
    let s = co.stats();
    let edges = r
        .merged
        .all_edges()
        .filter(|e| e.category == glia_code_domain::edge_category::CO_CHANGES)
        .count();
    eprintln!("files={} pairs={} co_changes_edges={edges}", files.len(), s.pairs);
    assert_eq!(s.snapshots, 1);
    assert!(s.commits <= 2000);
    assert!(s.pairs > edges);
}
