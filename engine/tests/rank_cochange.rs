//! EA.3: the ranked file space (`rank::FileIndex`, rank_eval's `index_graph`
//! candidate rule) and the co-change index (`rank::CochangeIndex`, rank_eval's
//! `cnt` / `co` over `git log --no-renames`) with its C0 signal.
//!
//! The snapshots are synthetic (`write_history`, no git), so every count is
//! exact and every C0 is compared with `==` against the literal expression.

use std::collections::BTreeMap;
use std::path::Path;

use glia_code_domain::snapshots::{HistoryCommit, HistoryFile, HistoryMeta, write_history};
use glia_engine::generate_one;
use glia_engine::rank::{CochangeHistory, CochangeIndex, FileIndex, NOT_CODE_EXTS, RankCache, c0};
use glia_graph::MergedGraph;

const T0: i64 = 1_767_225_600;

const CORE: &str = "svc/core.py";
const A: &str = "svc/a.py";
const B: &str = "svc/b.py";
const C: &str = "svc/c.py";
const PAGE: &str = "web/page.ts";
const PB: &str = "svc/pb.py";

fn file(p: &str, from: Option<&str>) -> HistoryFile {
    HistoryFile { p: p.to_string(), a: Some(1), d: Some(0), from: from.map(str::to_string) }
}

/// Commits from `groups` given oldest first, returned newest first (the
/// snapshot's order).
fn commits(groups: Vec<(Vec<HistoryFile>, usize)>) -> Vec<HistoryCommit> {
    let mut out = Vec::new();
    let mut i = 0usize;
    for (files, n) in groups {
        for _ in 0..n {
            i += 1;
            out.push(HistoryCommit {
                c: format!("{i:04}{}", "0".repeat(36)),
                t: T0 + i64::try_from(i).expect("small") * 3_600,
                files: files.clone(),
            });
        }
    }
    out.reverse();
    out
}

fn plain(paths: &[&str]) -> Vec<HistoryFile> {
    paths.iter().map(|p| file(p, None)).collect()
}

fn write_tree(root: &Path, files: &[(String, String)], history: Option<&[HistoryCommit]>) {
    for (p, text) in files {
        let path = root.join(p);
        std::fs::create_dir_all(path.parent().expect("parent")).expect("mkdir");
        std::fs::write(path, text).expect("write");
    }
    if let Some(h) = history {
        let head = h.first().map_or_else(|| "0".repeat(40), |c| c.c.clone());
        write_history(root, HistoryMeta::new(head, 2000, None, String::new()), h, &[]).expect("write snapshot");
    }
}

fn gen_file(i: usize) -> String {
    format!("svc/gen{i:02}.py")
}

fn doc_file(i: usize) -> String {
    format!("docs/n{i:02}.md")
}

fn main_tree_files() -> Vec<(String, String)> {
    let mut f: Vec<(String, String)> = vec![
        (CORE.into(), "from svc.c import helper\n\n\ndef core():\n    return helper()\n".into()),
        (A.into(), "def a_fn():\n    return 1\n".into()),
        (B.into(), "def b_fn():\n    return 2\n".into()),
        (C.into(), "def helper():\n    return 3\n".into()),
        (PAGE.into(), "export function renderPage(t: string): string {\n  return t;\n}\n".into()),
        (PB.into(), "# Code generated by protoc-gen-py. DO NOT EDIT.\n\n\ndef pb_fn():\n    return 4\n".into()),
        ("README.md".into(), "# demo\n".into()),
        ("conf/app.yaml".into(), "key: value\n".into()),
    ];
    for i in 0..30 {
        f.push((gen_file(i), format!("def gen_{i}():\n    return {i}\n")));
        f.push((doc_file(i), format!("# note {i}\n")));
    }
    f
}

fn main_history() -> Vec<HistoryCommit> {
    let mut wide: Vec<String> = vec![CORE.into()];
    wide.extend((0..30).map(gen_file));
    let mut docs: Vec<String> = vec![CORE.into()];
    docs.extend((0..30).map(doc_file));
    let refs = |v: &Vec<String>| v.iter().map(|p| file(p, None)).collect::<Vec<_>>();
    commits(vec![
        (plain(&[CORE, C]), 5),
        (plain(&[CORE, PAGE]), 4),
        (plain(&[CORE, B]), 2),
        (plain(&[CORE]), 3),
        (plain(&[CORE, "README.md", "conf/app.yaml"]), 1),
        (refs(&wide), 1),
        (refs(&docs), 1),
    ])
}

struct Built {
    _dir: tempfile::TempDir,
    merged: MergedGraph,
    roots: BTreeMap<u64, String>,
    labels: BTreeMap<u64, String>,
}

fn build(files: &[(String, String)], history: Option<&[HistoryCommit]>) -> Built {
    let d = tempfile::tempdir().expect("tempdir");
    write_tree(d.path(), files, history);
    let r = generate_one(&d.path().to_string_lossy()).expect("build");
    Built { merged: r.merged, roots: r.repo_roots, labels: r.repo_labels, _dir: d }
}

fn ix(files: &FileIndex, p: &str) -> u32 {
    let repo = files.repo(0);
    files.index_of(repo, p).unwrap_or_else(|| panic!("{p} is a candidate"))
}

