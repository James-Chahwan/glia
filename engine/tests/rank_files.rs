/// rank_eval `ref_config(None)` + `undirected(None, Direction::Undirected)`,
/// with the tuning grid's damping override for PT*.
fn ref_cfg(damping: f64) -> ActivationConfig {
    let mut c = CODE_TABLES.activation_config(None);
    c.damping = 0.5;
    c.max_iterations = 100;
    c.epsilon = 1e-6;
    c.direction = Direction::Undirected;
    c.top_k = usize::MAX;
    c.damping = damping;
    c
}

struct Ppr {
    n: usize,
    damping: f64,
    max_iter: usize,
    eps: f64,
    start: Vec<usize>,
    inc: Vec<(usize, f64)>,
    out_w: Vec<f64>,
    dangling: Vec<usize>,
}

impl Ppr {
    fn build(
        n: usize,
        id_to_idx: &HashMap<NodeId, usize>,
        edges: &[&Edge],
        cfg: &ActivationConfig,
    ) -> Self {
        let mut events: Vec<(usize, usize, f64)> = Vec::new();
        let mut out_w = vec![0.0; n];
        for e in edges {
            let w = cfg.edge_weights.get(&e.category).copied().unwrap_or(1.0);
            if w <= 0.0 {
                continue;
            }
            let (Some(&fi), Some(&ti)) = (id_to_idx.get(&e.from), id_to_idx.get(&e.to)) else {
                continue;
            };
            match cfg.direction {
                Direction::Forward => {
                    events.push((ti, fi, w));
                    out_w[fi] += w;
                }
                Direction::Backward => {
                    events.push((fi, ti, w));
                    out_w[ti] += w;
                }
                Direction::Undirected => {
                    events.push((ti, fi, w));
                    events.push((fi, ti, w));
                    out_w[fi] += w;
                    out_w[ti] += w;
                }
            }
        }
        let mut start = vec![0usize; n + 1];
        for e in &events {
            start[e.0 + 1] += 1;
        }
        for i in 0..n {
            start[i + 1] += start[i];
        }
        let mut cursor = start.clone();
        let mut inc = vec![(0usize, 0.0f64); events.len()];
        for e in &events {
            let c = cursor[e.0];
            inc[c] = (e.1, e.2);
            cursor[e.0] += 1;
        }
        let dangling = (0..n).filter(|&j| out_w[j] == 0.0).collect();
        Ppr {
            n,
            damping: cfg.damping,
            max_iter: cfg.max_iterations,
            eps: cfg.epsilon,
            start,
            inc,
            out_w,
            dangling,
        }
    }

    fn uniform(seeds: &[usize]) -> Vec<(usize, f64)> {
        let w = 1.0 / seeds.len() as f64;
        seeds.iter().map(|&s| (s, w)).collect()
    }

    fn power(&self, pers: &[(usize, f64)]) -> Vec<f64> {
        let n = self.n;
        if n == 0 || pers.is_empty() {
            return vec![0.0; n];
        }
        let mut personalization = vec![0.0; n];
        for &(i, w) in pers {
            personalization[i] = w;
        }
        let d = self.damping.clamp(0.01, 0.99);
        let mut scores = personalization.clone();
        let mut new_scores = vec![0.0; n];
        for _ in 0..self.max_iter {
            let dangling_sum: f64 = self.dangling.iter().map(|&j| scores[j]).sum();
            for i in 0..n {
                let propagated: f64 = self.inc[self.start[i]..self.start[i + 1]]
                    .iter()
                    .map(|&(j, w)| {
                        if self.out_w[j] > 0.0 {
                            scores[j] * w / self.out_w[j]
                        } else {
                            0.0
                        }
                    })
                    .sum();
                new_scores[i] = (1.0 - d) * personalization[i]
                    + d * (propagated + dangling_sum * personalization[i]);
            }
            let diff: f64 = scores
                .iter()
                .zip(new_scores.iter())
                .map(|(a, b)| (a - b).abs())
                .sum();
            std::mem::swap(&mut scores, &mut new_scores);
            if diff < self.eps {
                break;
            }
        }
        scores
    }
}

fn better(a: &Key, ia: usize, b: &Key, ib: usize) -> bool {
    for i in 0..3 {
        if a[i] > b[i] {
            return true;
        }
        if a[i] < b[i] {
            return false;
        }
    }
    ia < ib
}

fn scalar(v: &[f64]) -> Vec<Key> {
    v.iter().map(|&s| [s, 0.0, 0.0]).collect()
}

fn lex2(a: &[f64], b: &[f64]) -> Vec<Key> {
    a.iter().zip(b).map(|(&x, &y)| [x, y, 0.0]).collect()
}

struct Oracle<'a> {
    files: &'a FileIndex,
    id_to_idx: HashMap<NodeId, usize>,
    p1: Ppr,
    pt: Ppr,
    adj: Adjacency,
}

impl<'a> Oracle<'a> {
    fn new(merged: &MergedGraph, files: &'a FileIndex) -> Self {
        let all_ids = merged.node_ids();
        let id_to_idx: HashMap<NodeId, usize> =
            all_ids.iter().enumerate().map(|(i, &id)| (id, i)).collect();
        let edges: Vec<&Edge> = merged.all_edges().collect();
        let p1 = Ppr::build(all_ids.len(), &id_to_idx, &edges, &ref_cfg(0.5));
        let pt = Ppr::build(all_ids.len(), &id_to_idx, &edges, &ref_cfg(0.85));
        let adj = Adjacency::carry(merged, &CODE_TABLES);
        Oracle {
            files,
            id_to_idx,
            p1,
            pt,
            adj,
        }
    }

    fn file_pool(&self, v: &[f64], sum: bool) -> Vec<f64> {
        (0..self.files.len() as u32)
            .map(|f| {
                let mut acc = 0.0f64;
                for u in self.files.nodes(f) {
                    let s = v[self.id_to_idx[u]];
                    if sum {
                        acc += s;
                    } else {
                        acc = acc.max(s);
                    }
                }
                acc
            })
            .collect()
    }

    fn bfs_key(&self, seed_ids: &[NodeId]) -> Vec<Key> {
        let nf = self.files.len();
        let b = reach::bfs(&self.adj, seed_ids, Walk::Both, usize::MAX);
        let mut depth = vec![f64::INFINITY; nf];
        for r in &b.reached {
            if let Some(f) = self.files.file_of_node(r.id) {
                let d = &mut depth[f as usize];
                *d = d.min(r.depth as f64);
            }
        }
        (0..nf as u32)
            .map(|f| {
                let fu = f as usize;
                [
                    if depth[fu].is_finite() {
                        -depth[fu]
                    } else {
                        -1e9
                    },
                    self.files.degree(f),
                    0.0,
                ]
            })
            .collect()
    }

    /// The six rankings' keys for `seeds`, by harness name.
    fn keys(&self, seeds: &[u32], c0v: &[f64]) -> Vec<(&'static str, Vec<Key>)> {
        let seed_ids: Vec<NodeId> = seeds
            .iter()
            .flat_map(|&f| self.files.nodes(f).iter().copied())
            .collect();
        let nodes: Vec<usize> = seed_ids.iter().map(|id| self.id_to_idx[id]).collect();
        let pers = Ppr::uniform(&nodes);
        let p1 = self.file_pool(&self.p1.power(&pers), false);
        let pt = self.file_pool(&self.pt.power(&pers), true);
        let b0 = self.bfs_key(&seed_ids);
        let nf = self.files.len();
        vec![
            ("P1", scalar(&p1)),
            ("PT*", scalar(&pt)),
            ("B0", b0.clone()),
            ("H10", lex2(c0v, &p1)),
            ("H10[PT*]", lex2(c0v, &pt)),
            (
                "H10[B0]",
                (0..nf).map(|f| [c0v[f], b0[f][0], b0[f][1]]).collect(),
            ),
        ]
    }

    /// rank_eval's C0 for k seeds (`r3_tqueries`): per seed in order,
    /// co(s, f) / (count(s) + 1).
    fn c0(h: &dyn CochangeHistory, seeds: &[u32], nf: usize) -> Vec<f64> {
        let mut acc: BTreeMap<u32, f64> = BTreeMap::new();
        for &s in seeds {
            let d = f64::from(h.count(s)) + 1.0;
            for &(f, x) in h.cochanged(s) {
                *acc.entry(f).or_default() += f64::from(x) / d;
            }
        }
        let mut v = vec![0.0; nf];
        for (f, s) in acc {
            v[f as usize] = s;
        }
        v
    }
}

/// rank_eval `order` with every seed excluded (`eval_ex`'s ranking).
fn oracle_order(key: &[Key], seeds: &[u32]) -> Vec<u32> {
    let mut ix: Vec<usize> = (0..key.len())
        .filter(|f| !seeds.contains(&(*f as u32)))
        .collect();
    ix.sort_by(|&a, &b| {
        if better(&key[a], a, &key[b], b) {
            std::cmp::Ordering::Less
        } else if a == b {
            std::cmp::Ordering::Equal
        } else {
            std::cmp::Ordering::Greater
        }
    });
    ix.into_iter().map(|f| f as u32).collect()
}

fn bits(k: &[Key]) -> Vec<[u64; 3]> {
    k.iter()
        .map(|x| [x[0].to_bits(), x[1].to_bits(), x[2].to_bits()])
        .collect()
}

const SIX: [&str; 6] = ["P1", "PT*", "B0", "H10", "H10[PT*]", "H10[B0]"];

#[test]
fn six_rankings_equal_the_oracle_in_bits() {
    let b = build();
    let cache = RankCache::new("answer", &b.roots, &b.labels);
    cache.guard(&b.merged);
    let files = cache.files(&b.merged);
    let n = files.len();
    let oracle = Oracle::new(&b.merged, &files);
    let co = cache.cochange(&b.merged);
    let (core, a) = (ix(&files, CORE), ix(&files, A));
    for seeds in [vec![core], vec![core, a]] {
        let c0v = Oracle::c0(&*co, &seeds, n);
        let want = oracle.keys(&seeds, &c0v);
        for (name, key) in &want {
            let r = Ranking::from_harness_name(name).expect("harness name");
            let got = rank_files(&b.merged, &cache, &seeds, &[], r);
            assert_eq!(got.ranking, r);
            assert_eq!(got.seed_files, seeds);
            assert_eq!(bits(&got.keys), bits(key), "{name} keys, seeds {seeds:?}");
            assert_eq!(
                got.order,
                oracle_order(key, &seeds),
                "{name} order, seeds {seeds:?}"
            );
            assert!(
                seeds.iter().all(|s| got.position(*s).is_none()),
                "{name}: a seed file is never listed"
            );
            let c0_bits: Vec<u64> = got.c0.iter().map(|x| x.to_bits()).collect();
            if r.cochange_first {
                assert_eq!(
                    c0_bits,
                    c0v.iter().map(|x| x.to_bits()).collect::<Vec<_>>(),
                    "{name} c0"
                );
            } else {
                assert!(
                    got.c0.iter().all(|&x| x == 0.0),
                    "{name}: no co-change read"
                );
            }
            // rank_files_with_c0 given the same C0: bit-equal.
            let given = c0(&*co, &seeds, n);
            let with = rank_files_with_c0(&b.merged, &cache, &seeds, &[], r, Some(&given));
            assert_eq!(bits(&with.keys), bits(&got.keys), "{name} with_c0");
            assert_eq!(with.order, got.order);
            // base_keys(uniform) is the structural key of the three plain rankings.
            if !r.cochange_first {
                let seed_ids: Vec<NodeId> = seeds
                    .iter()
                    .flat_map(|&f| files.nodes(f).iter().copied())
                    .collect();
                let w = 1.0 / seed_ids.len() as f64;
                let pers: Vec<(NodeId, f64)> = seed_ids.iter().map(|&id| (id, w)).collect();
                assert_eq!(
                    bits(&base_keys(&b.merged, &cache, &pers, r.base)),
                    bits(&got.keys),
                    "{name} base_keys"
                );
            }
        }
        assert_eq!(want.len(), SIX.len());
    }
}

#[test]
fn default_ranking_lifts_cochange_and_leaves_out_seeds_and_docs() {
    let b = build();
    let cache = RankCache::new("answer", &b.roots, &b.labels);
    let files = cache.files(&b.merged);
    let paths: Vec<&str> = (0..files.len() as u32).map(|f| files.path(f)).collect();
    assert!(
        !paths.contains(&GUIDE),
        "docs/guide.md is no candidate: {paths:?}"
    );
    let core = ix(&files, CORE);
    let fr = rank_files(&b.merged, &cache, &[core], &[], Ranking::default());
    assert_eq!(fr.ranking.harness_name(), "H10");
    let first: Vec<&str> = fr.order.iter().take(3).map(|&f| files.path(f)).collect();
    assert_eq!(first, [C, PAGE, B]);
    assert_eq!(fr.c0[ix(&files, C) as usize], 5.0 / 17.0);
    assert_eq!(fr.c0[ix(&files, PAGE) as usize], 4.0 / 17.0);
    assert!(fr.position(core).is_none());
    assert_eq!(fr.order.len(), files.len() - 1);

    // top(): ranks, labels, rows.
    let mut rows = BTreeMap::new();
    rows.insert(ix(&files, C), 2usize);
    let top = fr.top(&files, 2, &rows);
    assert_eq!(top.len(), 2);
    assert_eq!((top[0].rank, top[0].file.as_str(), top[0].rows), (1, C, 2));
    assert_eq!(
        (top[1].rank, top[1].file.as_str(), top[1].rows),
        (2, PAGE, 0)
    );
    assert_eq!(top[0].cochange, 5.0 / 17.0);
    assert!(top[0].ppr.is_some() && top[0].depth.is_none());
    assert_eq!(
        top[0].repo,
        b.labels.values().next().cloned().unwrap_or_default()
    );

    // B0: depth reported, no ppr.
    let bfs = rank_files(
        &b.merged,
        &cache,
        &[core],
        &[],
        Ranking::new(RankBase::Bfs, false),
    );
    let t = bfs.top(&files, 1, &BTreeMap::new());
    assert!(t[0].ppr.is_none());
    assert!(t[0].depth.is_some(), "the best B0 file is reached: {t:?}");

    // order_rows over the H10 ranking: c.py's row lifts above a page row
    // only by c0; rows of a file with no c0 keep their input order.
    let (c, page, a, d) = (
        ix(&files, C),
        ix(&files, PAGE),
        ix(&files, A),
        ix(&files, D),
    );
    let rf = [Some(a), Some(page), None, Some(d), Some(c), Some(core)];
    let perm = order_rows(&rf, &[core], &fr).expect("a reorder");
    assert_eq!(perm, [4, 1, 0, 2, 3, 5]);
    let head = rank_files(&b.merged, &cache, &[core], &[], Ranking::head());
    assert_eq!(
        order_rows(&rf, &[core], &head),
        None,
        "P1 keeps the answer's own order"
    );
}

#[test]
fn ppr_wide_sums_d_above_a() {
    let b = build();
    let cache = RankCache::new("answer", &b.roots, &b.labels);
    let files = cache.files(&b.merged);
    let oracle = Oracle::new(&b.merged, &files);
    let (core, a, d) = (ix(&files, CORE), ix(&files, A), ix(&files, D));
    let n = files.len();
    let want = oracle.keys(&[core], &vec![0.0; n]);
    let pt = &want[1].1;
    assert!(
        pt[d as usize][0] > pt[a as usize][0],
        "the oracle sums d's two nodes above a: {:?} vs {:?}",
        pt[d as usize],
        pt[a as usize]
    );
    let fr = rank_files(
        &b.merged,
        &cache,
        &[core],
        &[],
        Ranking::new(RankBase::PprWide, false),
    );
    assert!(
        fr.position(d) < fr.position(a),
        "PT* puts svc/d.py above svc/a.py"
    );
}

