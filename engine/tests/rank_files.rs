//! EA.4: `rank::rank_files` computes rank_eval's measured file keys over the
//! whole FileIndex, and `order` is rank_eval's `order` (seed files left out,
//! `better`, ties to the smaller file index).
//!
//! The oracle below copies rank_eval.rs's arithmetic: `Ppr::build` /
//! `Ppr::power` over `merged.node_ids()` / `all_edges()` at `ref_config`'s
//! pins (`undirected(None, Direction::Undirected)`, and the tuning grid's
//! `d85` damping for PT*), `Ppr::uniform`, `file_pool`, `bfs_key` over the
//! carry adjacency, `scalar`, `lex2`, the `H10[B0]` key, the C0 loop of
//! `r3_tqueries` and `better` / `order`. Keys compare in f64 bits.

