type Key = [f64; 3];

const T0: i64 = 1_767_225_600;

const CORE: &str = "svc/core.py";
const A: &str = "svc/a.py";
const B: &str = "svc/b.py";
const C: &str = "svc/c.py";
const D: &str = "svc/d.py";
const PAGE: &str = "web/page.ts";
const PB: &str = "svc/pb.py";
const GUIDE: &str = "docs/guide.md";

fn file(p: &str) -> HistoryFile {
    HistoryFile {
        p: p.to_string(),
        a: Some(1),
        d: Some(0),
        from: None,
    }
}

/// Commits from `groups` given oldest first, returned newest first.
fn commits(groups: Vec<(Vec<HistoryFile>, usize)>) -> Vec<HistoryCommit> {
    let mut out = Vec::new();
    let mut i = 0usize;
    for (files, n) in groups {
        for _ in 0..n {
            i += 1;
            out.push(HistoryCommit {
                c: format!("{i:04}{}", "0".repeat(36)),
                t: T0 + i64::try_from(i).expect("small") * 3_600,
                files: files.clone(),
            });
        }
    }
    out.reverse();
    out
}

fn plain(paths: &[&str]) -> Vec<HistoryFile> {
    paths.iter().map(|p| file(p)).collect()
}

fn gen_file(i: usize) -> String {
    format!("svc/gen{i:02}.py")
}

fn doc_file(i: usize) -> String {
    format!("docs/n{i:02}.md")
}

/// EA.3's svc tree, plus svc/d.py (two functions calling core) and
/// docs/guide.md.
fn tree() -> Vec<(String, String)> {
    let mut f: Vec<(String, String)> = vec![
        (CORE.into(), "from svc.c import helper\n\n\ndef core():\n    return helper()\n".into()),
        (A.into(), "def a_fn():\n    return 1\n".into()),
        (B.into(), "def b_fn():\n    return 2\n".into()),
        (C.into(), "def helper():\n    return 3\n".into()),
        (
            D.into(),
            "from svc.core import core\n\n\ndef d1():\n    return core()\n\n\ndef d2():\n    return core() + 1\n".into(),
        ),
        (PAGE.into(), "export function renderPage(t: string): string {\n  return t;\n}\n".into()),
        (PB.into(), "# Code generated by protoc-gen-py. DO NOT EDIT.\n\n\ndef pb_fn():\n    return 4\n".into()),
        ("README.md".into(), "# demo\n".into()),
        (GUIDE.into(), "# Guide\n\nSee `core` in svc/core.py.\n".into()),
        ("conf/app.yaml".into(), "key: value\n".into()),
    ];
    for i in 0..30 {
        f.push((gen_file(i), format!("def gen_{i}():\n    return {i}\n")));
        f.push((doc_file(i), format!("# note {i}\n")));
    }
    f
}

fn history() -> Vec<HistoryCommit> {
    let mut wide: Vec<String> = vec![CORE.into()];
    wide.extend((0..30).map(gen_file));
    let mut docs: Vec<String> = vec![CORE.into()];
    docs.extend((0..30).map(doc_file));
    let refs = |v: &Vec<String>| v.iter().map(|p| file(p)).collect::<Vec<_>>();
    commits(vec![
        (plain(&[CORE, C]), 5),
        (plain(&[CORE, PAGE]), 4),
        (plain(&[CORE, B]), 2),
        (plain(&[CORE]), 3),
        (plain(&[CORE, "README.md", "conf/app.yaml"]), 1),
        (refs(&wide), 1),
        (refs(&docs), 1),
    ])
}

struct Built {
    _dir: tempfile::TempDir,
    merged: MergedGraph,
    roots: BTreeMap<u64, String>,
    labels: BTreeMap<u64, String>,
}

fn build() -> Built {
    let d = tempfile::tempdir().expect("tempdir");
    let root: &Path = d.path();
    for (p, text) in tree() {
        let path = root.join(p);
        std::fs::create_dir_all(path.parent().expect("parent")).expect("mkdir");
        std::fs::write(path, text).expect("write");
    }
    let h = history();
    let head = h.first().map_or_else(|| "0".repeat(40), |c| c.c.clone());
    write_history(
        root,
        HistoryMeta::new(head, 2000, None, String::new()),
        &h,
        &[],
    )
    .expect("write snapshot");
    let r = generate_one(&root.to_string_lossy()).expect("build");
    Built {
        merged: r.merged,
        roots: r.repo_roots,
        labels: r.repo_labels,
        _dir: d,
    }
}

fn ix(files: &FileIndex, p: &str) -> u32 {
    files
        .index_of(files.repo(0), p)
        .unwrap_or_else(|| panic!("{p} is a candidate"))
}

